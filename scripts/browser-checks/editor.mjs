// Editor features on the replica's Y.Doc (test env only): slash menu, mention, undo, image upload, moving a block.
import { chromium } from 'playwright'
const base = process.argv[2] ?? 'http://127.0.0.1:5183'
if (!/^http:\/\/127\.0\.0\.1:518[34]$/.test(base)) throw new Error(`not the test env: ${base}`)
const browser = await chromium.launch()
const context = await browser.newContext()
if (process.env.MODE === 'json') await context.addInitScript(() => localStorage.setItem('vasta.replica', 'off'))
const page = await context.newPage()
const problems = []
page.on('console', (m) => (m.type() === 'error' || m.type() === 'warning') && !/401/.test(m.text()) && problems.push(`${m.type()}: ${m.text()}`))
page.on('pageerror', (e) => problems.push(`pageerror: ${e.message}`))
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
async function until(check, what, timeout = 15000) {
  const start = Date.now()
  for (;;) {
    const value = await check()
    if (value) return value
    if (Date.now() - start > timeout) { console.log(problems.join('\n')); throw new Error(`timed out: ${what}`) }
    await sleep(250)
  }
}
const types = (doc) => (doc?.content ?? []).map((n) => n.type + (n.type === 'paragraph' || n.type === 'heading' ? `:${(n.content ?? []).map((c) => c.text ?? `[${c.type}]`).join('')}` : ''))
await page.goto(base)
await page.fill('#login-username', 'tester')
await page.fill('#login-password', 'test-password')
await page.click('button[type=submit]')
await page.waitForSelector('nav', { timeout: 30000 })
const spaces = await (await page.request.get(`${base}/api/spaces`)).json()
const bundle = await (await page.request.get(`${base}/api/spaces/${spaces[0].id}`)).json()
const pageType = bundle.types.find((t) => t.system === 'page')
const created = await (await page.request.post(`${base}/api/objects`, { headers: { 'x-requested-with': 'vasta' }, data: { typeId: pageType.id, title: 'Editor check' } })).json()
const target = (await (await page.request.get(`${base}/api/spaces/${spaces[0].id}/search?q=Daggerheart`)).json())[0]
await sleep(1500)
await page.goto(`${base}/o/${created.id}`)
await page.waitForSelector('.vasta-doc')
await page.click('.vasta-doc')
await sleep(150)
console.log('• slash menu: heading')
await page.keyboard.type('/head')
await sleep(300)
await page.keyboard.press('Enter')
await page.keyboard.type('A heading')
await page.keyboard.press('Enter')
await page.keyboard.type('Body text, see ')
console.log('• mention')
await page.keyboard.type('@Daggerh')
await until(async () => (await page.textContent('body')).includes('Daggerheart'), 'mention list')
await sleep(300)
await page.keyboard.press('Enter')
console.log('• undo')
await sleep(700)
await page.keyboard.type(' oops')
await sleep(100)
await page.keyboard.press('Meta+z')
await sleep(200)
const afterUndo = await page.textContent('.vasta-doc')
if (afterUndo.includes('oops')) throw new Error(`undo did not remove the typing: ${afterUndo}`)
console.log('• move the paragraph above the heading')
await page.keyboard.press('Meta+Shift+ArrowUp')
await sleep(200)
console.log('• image upload')
await page.keyboard.press('Meta+ArrowDown')
await page.keyboard.press('Enter')
await sleep(150)
const chooser = page.waitForEvent('filechooser')
await page.keyboard.type('/image')
await sleep(300)
await page.keyboard.press('Enter')
await (await chooser).setFiles(new URL('./dot.png', import.meta.url).pathname)
await until(async () => (await page.$('.vasta-doc img')) !== null, 'image shown')
const server = await until(async () => {
  const o = await (await page.request.get(`${base}/api/objects/${created.id}`)).json()
  const t = types(o.content.body)
  return t.some((x) => x.startsWith('objectEmbed')) && t.some((x) => x.includes('[mention]')) ? t : undefined
}, 'everything on the server')
console.log('  server:', JSON.stringify(server))
if (!server[0].startsWith('paragraph:Body text') || !server.includes('heading:A heading') || server.indexOf('heading:A heading') < 1) throw new Error('block order is not what was typed')
await page.reload()
await page.waitForSelector('.vasta-doc img', { timeout: 20000 })
console.log('  after reload:', JSON.stringify(await page.$$eval('.vasta-doc > *', (els) => els.map((e) => e.tagName + ':' + e.textContent.slice(0, 30)))))
if (problems.length) console.log(`console problems:\n  ${problems.join('\n  ')}`)
console.log('OK')
await browser.close()
