// Settings › Inbox (test env only): the word for reviewed items and fading. Captures one item, marks
// it in the inbox with the default word, renames the word, turns fading on and checks both the inbox
// and the daily note; then puts the defaults back. SHOTS=<dir> saves screenshots.
import { chromium } from 'playwright'
const base = process.argv[2] ?? 'http://127.0.0.1:5183'
if (!/^http:\/\/127\.0\.0\.1:518[34]$/.test(base)) throw new Error('test env only (5183/5184)')
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1000, height: 1000 } })
await page.goto(base)
await page.fill('#login-username', 'tester')
await page.fill('#login-password', 'test-password')
await page.click('button[type=submit]')
await page.waitForSelector('nav', { state: 'attached', timeout: 30000 })
const api = (method, path, body) => page.evaluate(async ([method, path, body]) => {
  const response = await fetch(path, { method, headers: { 'content-type': 'application/json', 'x-requested-with': 'vasta' }, ...(body ? { body: JSON.stringify(body) } : {}) })
  return response.json()
}, [method, path, body])
await api('PUT', '/api/auth/me', { inbox: null })
const text = `inbox check ${Date.now()}`
await page.goto(`${base}/inbox`)
// A capture through quick capture would need the dialog; the capture API with the session is simpler.
const spaces = await api('GET', '/api/spaces')
console.log('capture:', JSON.stringify(await api('POST', `/api/spaces/${spaces[0].id}/captures`, { text, channel: 'api' })).slice(0, 80))
await page.reload()
const item = page.locator('li', { hasText: text })
await item.waitFor()
const mark = item.getByTitle('Mark reviewed')
console.log('default title:', await mark.count() === 1 ? 'Mark reviewed' : 'missing')
await mark.click()
await page.waitForTimeout(300)
console.log('after marking, hidden:', (await item.count()) === 0, '| toggle:', (await page.getByRole('button', { name: /Show reviewed/ }).textContent()).trim())
await page.goto(`${base}/settings`)
const section = page.locator('#inbox')
await section.getByPlaceholder('Reviewed').fill('Triaged')
await section.getByPlaceholder('Reviewed').press('Enter')
await section.getByRole('checkbox').check()
await page.waitForTimeout(500)
console.log('settings:', (await section.textContent()).replace(/\s+/g, ' ').trim())
if (process.env.SHOTS) await section.screenshot({ path: `${process.env.SHOTS}/inbox-settings.png` })
await page.goto(`${base}/inbox`)
await page.getByRole('button', { name: /Show triaged/ }).click()
await item.waitFor()
console.log('renamed title:', await item.getByTitle('Mark not triaged').count() === 1, '| faded:', /opacity-55/.test(await item.getAttribute('class')))
if (process.env.SHOTS) await page.screenshot({ path: `${process.env.SHOTS}/inbox.png` })
await item.getByTitle('Open in the daily note').click()
const callout = page.locator('[data-capture-id]', { hasText: text })
await callout.waitFor()
console.log('daily note label:', (await callout.locator('button').textContent()).trim(), '| faded:', /opacity-55/.test(await callout.getAttribute('class')))
await api('PUT', '/api/auth/me', { inbox: null })
await page.reload()
await callout.waitFor()
console.log('defaults again:', (await callout.locator('button').textContent()).trim(), '| faded:', /opacity-55/.test(await callout.getAttribute('class')))
await browser.close()
